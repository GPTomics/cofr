    parts.append('## Falsification review')
    parts.append('')
    if not review:
        parts.append('None.')
        parts.append('')
    else:
        for rec in review:
            parts.append(_render_falsification_block(rec))
            parts.append('')

    parts.append('## Computed risks')
    parts.append('')
    if not computed_risks:
        parts.append('No computed risks.')
        parts.append('')
