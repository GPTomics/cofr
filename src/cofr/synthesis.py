def generate_next_decision(state, contradictions=None):
    '''Render artifacts/next_decision.md: the ranked next-decision scaffold.'''
    ranked, rationale_lines, _ = rank_next_decisions(state, contradictions=contradictions)

    parts = [HEADER, '', '# Recommended next decision', '']
    parts.append('## Top decision')
    parts.append('')
    if not ranked:
        parts.append('No decision to recommend -- no open questions and no decisions with eroded basis.')
        parts.append('')
    else:
        parts.append(_render_next_decision_candidate(ranked[0]))
        parts.append('')

    parts.append('## Runner-up decisions')
    parts.append('')
    runner_ups = ranked[1:4]
    if not runner_ups:
        parts.append('None.')
        parts.append('')
    else:
        for entry in runner_ups:
            parts.append(_render_next_decision_candidate(entry, abbreviated=True))
            parts.append('')

    parts.append('## Ranking rationale')
    parts.append('')
    for line in rationale_lines:
        parts.append(line)
    parts.append('')

    return '\n'.join(parts) + '\n'
