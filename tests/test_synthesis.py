def test_semantic_staleness_ignores_non_live_evidence():
    state = {
        'claims': [{'id': 'claim_a', 'status': 'provisionally_supported', 'last_updated': '2026-01-01T00:00:00Z'}],
        'evidence': [{'id': 'ev_old', 'status': 'deprecated', 'stale': True, 'last_updated': '2026-02-01T00:00:00Z', 'claim_links': [{'claim_id': 'claim_a'}]}],
        'decisions': [],
    }
    staleness, warnings = compute_semantic_staleness(state)
    assert staleness['claim_unchanged'] == []
    assert warnings == []
