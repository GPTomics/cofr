def test_compute_claim_evidence_counts():
    evidence = [
        {'id': 'ev_1', 'claim_links': [{'claim_id': 'c_a', 'polarity': 'supports'}]},
        {'id': 'ev_2', 'claim_links': [{'claim_id': 'c_a', 'polarity': 'opposes'}]},
        {'id': 'ev_3', 'claim_links': [{'claim_id': 'c_a', 'polarity': 'supports'}, {'claim_id': 'c_b', 'polarity': 'opposes'}]},
    ]
    counts_a = compute_claim_evidence_counts('c_a', evidence)
    assert counts_a == {'supports': 2, 'opposes': 1}
    counts_b = compute_claim_evidence_counts('c_b', evidence)
    assert counts_b == {'supports': 0, 'opposes': 1}


